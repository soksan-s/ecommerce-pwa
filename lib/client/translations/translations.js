export function useTranslation(lang) {
  const currentLang = lang === "km" ? "km" : "en";

  return useMemo(
    () => ({
      t: (key) => translations[currentLang]?.[key] || translations.en?.[key] || key,
      language: currentLang,
    }),
    [currentLang],
  );
}
